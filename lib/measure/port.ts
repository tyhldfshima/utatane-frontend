// 計測の送り口（measure port）。★形だけです。
//
// 正本：docs/design/utatane-completion-criteria.md §4（成長ループの8段）。
//   種 → 参加 → Contribution → Version → 公開 → TYP → 次の創作
//   正本が求めているのは「MVP開始時から、このループのどこで止まったかを測れること」だけです。
//
// ★正本の決まり：「イベント名・分析基盤・保存期間を今ここで固定する必要はありません。」
//   だからここでは、名前も分析基盤も保存期間も決めません。決めるのは**どの段の操作点か**だけです。
//   段の見分けには、正本 §4 の表の番号（M-1〜M-8）をそのまま使います。
//   これは**イベント名ではなく段の番号**なので、あとで名前を決めても、ここを書き直さずに済みます。
//
// ★送り口は1つだけ（lib/measure/index.ts）。画面は必ず measure() 経由で呼び、
//   どこへ送るかは画面の外（送り口の差し替え）で決めます。画面は1枚も書き直しません。

/** 正本 §4 の段の番号。★イベント名ではない。 */
export type LoopStage = 'M-1' | 'M-2' | 'M-3' | 'M-4' | 'M-5' | 'M-6' | 'M-7' | 'M-8'

/** 8段を、正本 §4 の表と同じ順で並べた物 */
export const LOOP_STAGES: readonly LoopStage[] = ['M-1', 'M-2', 'M-3', 'M-4', 'M-5', 'M-6', 'M-7', 'M-8']

/**
 * 段の呼び名（正本 §4 の表の「段」欄と同じ言葉）。
 * ★イベント名ではありません。人が読むためだけの物で、送り先へは渡しません。
 * ★正本とずれていないことは app/ui/measure.test.ts が見張ります。
 */
export const LOOP_STAGE_LABEL: Record<LoopStage, string> = {
  'M-1': '種',
  'M-2': '参加',
  'M-3': 'Contribution',
  'M-4': 'Contribution（採用）',
  'M-5': 'Version',
  'M-6': '公開',
  'M-7': 'TYP',
  'M-8': '次の創作',
}

/**
 * 送り口。画面の操作点から、その段を1回だけ知らせる。
 *
 * ★引数は段の番号ひとつだけです。名前・利用者・時刻・端末などは渡しません
 *  （渡す物を決めるのは、送り先を決める便です）。
 * ★戻り値はありません。画面は結果を待たず、見た目も動きも変わりません。
 */
export type MeasureSink = {
  mark(stage: LoopStage): void
}
